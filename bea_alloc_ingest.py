def main():
    obj = json.load(open(HOLD, encoding="utf-8"))
    funds = obj["funds"]
    n = 0
    for fid, arr in DATA.items():
        if fid not in funds:
            print("  [!] 缺 id", fid)
            continue
        funds[fid]["alloc"] = [{"label": l, "weight": w} for l, w in arr]
        funds[fid]["asOf"] = ASOF
        funds[fid]["src"] = SRC
        n += 1
    obj["updatedAt"] = int(time.time() * 1000)
    json.dump(obj, open(HOLD, "w", encoding="utf-8"), ensure_ascii=False, separators=(",", ":"))
    print("写入 %d 条" % n)


if __name__ == "__main__":
    main()
