def main():
    dry = "--dry" in sys.argv
    obj = json.load(open(HOLD, encoding="utf-8"))
    funds = obj["funds"]
    ok = 0
    for name, d in DATA.items():
        alloc = [{"label": l, "weight": w} for l, w in d["alloc"]]
        total = round(sum(w for _, w in d["alloc"]), 1)
        if abs(total - 100) > 0.6:
            print("  [!] %s 合计 %.1f%%（跳过，需复核）" % (name, total))
            continue
        for fid in d["ids"]:
            if fid not in funds:
                print("  [!] %s 缺少 id %s" % (name, fid))
                continue
            funds[fid]["alloc"] = alloc
            funds[fid]["asOf"] = ASOF
            funds[fid]["src"] = SRC
            ok += 1
    print("写入 %d 条（%d 只基金）" % (ok, len(DATA)))
    if dry:
        print("（--dry 未写盘）")
        return
    obj["updatedAt"] = int(time.time() * 1000)
    with open(HOLD, "w", encoding="utf-8") as fh:
        json.dump(obj, fh, ensure_ascii=False, separators=(",", ":"))
    print("已写入", HOLD)


if __name__ == "__main__":
    main()
